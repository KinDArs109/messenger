import { room } from "@messenger/shared";
import { prisma } from "../../db/client.js";
import { badRequest, notFound } from "../../lib/errors.js";
import { realtime } from "../../realtime/emitter.js";

/**
 * Удаления из хозяйской панели — вместе с рассылкой живым.
 *
 * Отдельно от маршрутов по двум причинам. Первая: удаление — это два
 * дела, а не одно. Убрать из базы мало; надо ещё сказать всем, кто
 * сейчас в мессенджере, иначе удалённое остаётся на экранах до
 * перезагрузки — сервер в списке, человек в составе, зелёный кружок
 * у того, кого больше нет.
 *
 * Вторая: до маршрутов проверке не дотянуться. Хозяйский раздел закрыт
 * второй дверью — кодом в Телеграм, — и это правильно, но проверить
 * через неё ничего нельзя: кода у проверки нет и быть не должно.
 * А здесь то же самое доступно напрямую, и рассылка проверяется
 * по-настоящему, а не на словах.
 */

/**
 * Удалить сервер целиком.
 *
 * Вместе с ним уходят каналы, переписка в них, состав и приглашения —
 * это и значит «удалить сервер».
 */
export async function удалитьСервер(
  id: string,
): Promise<{ удалён: string; людей: number }> {
  const сервер = await prisma.server.findUnique({
    where: { id },
    select: {
      name: true,
      _count: { select: { members: true, channels: true } },
    },
  });
  if (!сервер) throw notFound("Такого сервера нет");

  // Сообщения удаляем сами: канал уходит следом за сервером, а вот
  // сообщения держатся за автора, и без этого шага удаление упёрлось бы
  // в запрет базы.
  await prisma.$transaction([
    prisma.message.deleteMany({ where: { channel: { serverId: id } } }),
    prisma.server.delete({ where: { id } }),
  ]);

  /*
   * И говорим об этом всем, кто сейчас в мессенджере.
   *
   * Комната сокета живёт отдельно от базы: люди остаются в ней и после
   * того, как сервер удалён, — поэтому сказать им можно и нужно уже
   * после удаления.
   */
  realtime().to(room.server(id)).emit("server:delete", { id });

  return { удалён: сервер.name, людей: сервер._count.members };
}

/**
 * Удалить учётную запись.
 *
 * Со всеми оговорками, потому что отменить это нельзя. Себя удалить
 * не даём — иначе одним нажатием можно остаться без хозяина. Того,
 * у кого есть свои серверы, тоже: вместе с ним исчезли бы каналы
 * и переписка людей, которые ни при чём.
 */
export async function удалитьЧеловека(
  id: string,
  хозяинId: string,
): Promise<{ удалён: string; сообщений: number }> {
  if (id === хозяинId) throw badRequest("SELF", "Себя удалить нельзя");

  const кто = await prisma.user.findUnique({
    where: { id },
    select: {
      username: true,
      _count: { select: { ownedServers: true, messages: true } },
    },
  });
  if (!кто) throw notFound("Такого человека нет");

  if (кто._count.ownedServers > 0) {
    throw badRequest(
      "OWNS_SERVERS",
      `У ${кто.username} свои серверы (${кто._count.ownedServers}). Сначала удалите их — вместе с сервером уходит и переписка на нём`,
    );
  }

  // Где он состоял — узнаём до удаления: после в базе не останется
  // ничего, кому об этом рассказывать.
  const состоял = await prisma.serverMember.findMany({
    where: { userId: id },
    select: { serverId: true },
  });

  /*
   * Сообщения удаляем сами, и это не мелочь.
   *
   * У сообщения автор — обычная связь без «удалять следом»: база
   * намеренно не даёт стереть человека, за которым осталась переписка,
   * иначе чужие разговоры превращались бы в дыры. Панель раньше
   * налетала на этот запрет и показывала «внутреннюю ошибку сервера» —
   * то есть ничего не объясняла.
   *
   * Правильный ответ здесь — не обходить запрет, а сделать то, что
   * хозяин и имеет в виду под «удалить учётную запись»: убрать человека
   * вместе с тем, что он написал. Всё остальное — участия в серверах,
   * дружбы, прочитанное, вложения — уходит за ним само.
   *
   * Одной сделкой: если на середине что-то пойдёт не так, не должно
   * остаться половины человека.
   */
  const [сообщений] = await prisma.$transaction([
    prisma.message.deleteMany({ where: { authorId: id } }),
    prisma.user.delete({ where: { id } }),
  ]);

  /*
   * И сразу рассказываем живым.
   *
   * Без этого удалённый оставался на экранах до перезагрузки: висел
   * в списке участников, здоровался зелёным кружком и открывался
   * в переписке. Хозяин видел, что удалил, а остальные — нет.
   */
  for (const { serverId } of состоял) {
    realtime()
      .to(room.server(serverId))
      .emit("member:leave", { serverId, userId: id });
  }

  // Его собственные окна закрываем: учётной записи больше нет,
  // а мессенджер об этом узнал бы только через четверть часа, когда
  // истечёт токен, — и всё это время делал бы вид, что всё в порядке.
  realtime().in(room.user(id)).disconnectSockets(true);

  return { удалён: кто.username, сообщений: сообщений.count };
}
