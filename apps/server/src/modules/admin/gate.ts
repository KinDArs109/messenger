import {
  createHash,
  randomBytes,
  randomInt,
  timingSafeEqual,
} from "node:crypto";
import type { RequestHandler } from "express";
import { prisma } from "../../db/client.js";
import { env } from "../../config/env.js";
import { badRequest, notFound, unauthorized } from "../../lib/errors.js";
import { sendTelegram, telegramReady } from "../../lib/telegram.js";
import { currentUserId } from "../../middleware/auth.js";

/**
 * Вторая дверь в хозяйский раздел: код в Телеграм.
 *
 * Первая — обычный вход в мессенджер: пароль и код из почты. Этого
 * мало для раздела, где лежат почты всех до единого и кнопка «удалить
 * человека»: почтовый ящик — вещь, которую можно потерять вместе
 * с телефоном, и тогда потеряется всё сразу.
 *
 * Поэтому вторая дверь открывается в другом месте: код приходит тем же
 * ботом, что и тревоги сторожа. Смысл не только в том, что чужому
 * нужен ещё и Телеграм. Смысл в том, что хозяин узнаёт о любой попытке
 * в ту же секунду — даже о своей, а значит, и о чужой.
 *
 * Всё держится в памяти сервера: коды живут пять минут, и переживать
 * перезапуск им незачем.
 */

/** Столько живёт код. Пять минут — это «пришло, посмотрел, ввёл»,
 *  и слишком мало, чтобы забытое открытым сообщение стало ключом. */
const КОД_ЖИВЁТ = 5 * 60 * 1000;

/** Столько живёт открытая дверь. Полчаса хватает на любые хозяйские
 *  дела, а забытая открытой панель через полчаса закроется сама. */
const ДВЕРЬ_ЖИВЁТ = 30 * 60 * 1000;

/** Попыток на код. */
const ПОПЫТОК = 3;

/** Чаще этого о чужих стуках в дверь не пишем: иначе тот, кто узнал
 *  адрес, может засыпать хозяина сообщениями просто перезагружая
 *  страницу. */
const ПАУЗА_ТРЕВОГ = 5 * 60 * 1000;

const хеш = (строка: string) =>
  createHash("sha256").update(строка).digest("hex");

interface Ожидание {
  userId: string;
  hash: string;
  до: number;
  попыток: number;
}

interface Дверь {
  userId: string;
  до: number;
}

const ожидания = new Map<string, Ожидание>();
const двери = new Map<string, Дверь>();
let последняяТревога = 0;

/** Подчищаем протухшее: карты маленькие, но расти без конца им незачем. */
function подмести(): void {
  const сейчас = Date.now();
  for (const [ключ, что] of ожидания)
    if (что.до < сейчас) ожидания.delete(ключ);
  for (const [ключ, что] of двери) if (что.до < сейчас) двери.delete(ключ);
}

/** Хозяин ли это. Имя лежит в настройках сервера; пока его нет,
 *  раздела нет вовсе. */
export async function хозяин(userId: string): Promise<boolean> {
  if (!env.ADMIN_USERNAME) return false;
  const кто = await prisma.user.findUnique({
    where: { id: userId },
    select: { username: true },
  });
  return кто?.username === env.ADMIN_USERNAME;
}

/** Сообщить хозяину, что в дверь постучал чужой. Не чаще раза
 *  в пять минут — см. ПАУЗА_ТРЕВОГ. */
export function чужойСтучал(): void {
  if (Date.now() - последняяТревога < ПАУЗА_ТРЕВОГ) return;
  последняяТревога = Date.now();
  void sendTelegram(
    "⚠️ Кто-то постучался в хозяйскую панель мессенджера и не прошёл: " +
      "учётная запись не хозяйская.",
  );
}

/**
 * Первый шаг: выдать код и отправить его в Телеграм.
 *
 * Возвращает пропуск — по нему потом принимается код. Сам код наружу
 * не отдаётся никогда, даже хозяину: смысл ровно в том, что за ним
 * надо пойти в другое место.
 */
export async function попроситьКод(
  userId: string,
): Promise<{ ticket: string }> {
  подмести();

  if (!telegramReady()) {
    // Закрываемся, а не открываемся. Панель без предупреждения хозяину
    // — это ровно то, чего он просил не допускать; уж лучше он
    // не попадёт внутрь сам и починит бота.
    throw badRequest(
      "NO_TELEGRAM",
      "Сторож в Телеграме не настроен — панель закрыта. Пропишите ключ бота на сервере.",
    );
  }

  const код = randomInt(0, 1_000_000).toString().padStart(6, "0");
  const ticket = randomBytes(18).toString("base64url");

  ожидания.set(ticket, {
    userId,
    hash: хеш(код),
    до: Date.now() + КОД_ЖИВЁТ,
    попыток: 0,
  });

  const ушло = await sendTelegram(
    `🔐 Открывают хозяйскую панель мессенджера.\n\nКод: ${код}\n\n` +
      "Действует 5 минут. Если это не вы — значит, кто-то знает ваш пароль " +
      "и почту: смените пароль прямо сейчас.",
  );

  if (!ушло) {
    ожидания.delete(ticket);
    throw badRequest(
      "TELEGRAM_FAILED",
      "Не удалось отправить код в Телеграм — попробуйте ещё раз",
    );
  }

  return { ticket };
}

/** Второй шаг: принять код и открыть дверь на полчаса. */
export function принятьКод(
  ticket: string,
  код: string,
): { token: string; до: number } {
  подмести();

  const ждём = ожидания.get(ticket);
  if (!ждём) throw unauthorized("Код устарел — начните заново");

  if (ждём.попыток >= ПОПЫТОК) {
    ожидания.delete(ticket);
    void sendTelegram(
      "⚠️ В хозяйскую панель три раза подряд ввели неверный код.",
    );
    throw badRequest("TOO_MANY", "Слишком много попыток — начните заново");
  }

  const дано = Buffer.from(хеш(код.trim()));
  const ждали = Buffer.from(ждём.hash);
  const сошлось = дано.length === ждали.length && timingSafeEqual(дано, ждали);

  if (!сошлось) {
    ждём.попыток += 1;
    throw badRequest("BAD_CODE", "Код не подошёл");
  }

  ожидания.delete(ticket);

  const token = randomBytes(24).toString("base64url");
  const до = Date.now() + ДВЕРЬ_ЖИВЁТ;
  двери.set(хеш(token), { userId: ждём.userId, до });

  void sendTelegram(
    "✅ Хозяйская панель открыта. Если это не вы — смените пароль и напишите мне.",
  );

  return { token, до };
}

/**
 * Проверка на каждом хозяйском запросе.
 *
 * Открытая дверь — не замена входу, а добавка к нему: пропуск
 * действителен только вместе с обычным токеном того же человека.
 * Так украденный пропуск сам по себе ничего не даёт.
 */
export const требуетсяДверь: RequestHandler = (req, _res, next) => {
  подмести();

  const пропуск = req.headers["x-admin"];
  const дверь =
    typeof пропуск === "string" ? двери.get(хеш(пропуск)) : undefined;

  if (!дверь || дверь.до < Date.now() || дверь.userId !== currentUserId(req)) {
    // «Не найдено», как и всё в этом разделе: чужому незачем понимать,
    // на каком именно шаге его остановили.
    next(notFound("Раздел не найден"));
    return;
  }

  next();
};

/**
 * До какого времени открыта дверь.
 *
 * Панель показывает это вслух и заранее просит новый код, а не падает
 * посреди дела с «раздел не найден». Полчаса — срок жёсткий: панель,
 * забытая открытой, должна закрыться сама, сколько бы в неё ни тыкали.
 */
export function докогдаДверь(пропуск: string): number | null {
  const дверь = двери.get(хеш(пропуск));
  return дверь && дверь.до > Date.now() ? дверь.до : null;
}

/** Закрыть дверь по своей воле — кнопкой «выйти» в панели. */
export function закрытьДверь(пропуск: string): void {
  двери.delete(хеш(пропуск));
}
