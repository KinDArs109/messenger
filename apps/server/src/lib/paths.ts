import { existsSync } from "node:fs";
import path from "node:path";

/**
 * Где что лежит — от корня сервера, а не от глубины файла.
 *
 * Раньше каждый считал путь сам: «отсюда два шага вверх». Это работало
 * ровно до того дня, когда сервер собрали в один файл: собранный лежит
 * не там, где исходный, шагов вверх нужно другое число — и папка
 * с загруженными файлами превращается в соседнюю, которой нет.
 * Заметить это можно было только по пропавшим аватаркам.
 *
 * Поэтому считаем один раз и от опоры, которая не зависит от сборки:
 * идём вверх, пока не найдём package.json сервера.
 */
function корень(): string {
  // Явно заданный корень — на случай необычной раскладки.
  const заданный = process.env.SERVER_ROOT;
  if (заданный) return path.resolve(заданный);

  let где = import.meta.dirname;
  for (let шаг = 0; шаг < 6; шаг += 1) {
    if (existsSync(path.join(где, "package.json"))) return где;
    const выше = path.dirname(где);
    if (выше === где) break;
    где = выше;
  }

  // Не нашли — значит запущены как-то совсем иначе; тогда честнее
  // отталкиваться от рабочей папки, чем молча писать не туда.
  return process.cwd();
}

/** Корень пакета сервера: .../apps/server. */
export const КОРЕНЬ_СЕРВЕРА = корень();

/** Загруженные файлы: аватарки, картинки, голосовые. */
export const UPLOADS_DIR = path.join(КОРЕНЬ_СЕРВЕРА, "uploads");

/** Собранный клиент. Его отдаёт этот же процесс — один адрес,
 *  один порт, никакого CORS. */
export const CLIENT_DIST = path.join(КОРЕНЬ_СЕРВЕРА, "..", "web", "dist");
