// Подпорки для сквозной проверки раздачи (check-sfu.cjs).
//
// Две штуки, и обе — про окружение проверки, а не про мессенджер.

/*
 * 1. Счётчик соединений.
 *
 * Главный вопрос проверки — сколько раз показывающий отправил
 * картинку. Спросить об этом можно только у самих соединений, а их
 * заводит мессенджер внутри себя и наружу не отдаёт. Поэтому
 * подменяем сам класс: он остаётся тем же, только каждое созданное
 * соединение попадает ещё и в список.
 *
 * Через Proxy, а не обёрткой-функцией: обёртка теряет new.target,
 * и браузер отказывается работать с таким соединением вовсе.
 */
const Прежний = window.RTCPeerConnection;
window.__соединения = [];

window.RTCPeerConnection = new Proxy(Прежний, {
  construct(цель, доводы) {
    const соединение = Reflect.construct(цель, доводы);
    window.__соединения.push(соединение);
    return соединение;
  },
});

/*
 * 2. Своя камера вместо поддельной.
 *
 * У Chromium есть встроенная поддельная камера — тем и удобны такие
 * проверки. Беда в том, что здесь она живёт ровно секунду: дорожка
 * сама уходит в ended, и мессенджер честно прекращает показ, потому
 * что для него это «камеру выдернули из гнезда». Замерено отдельно,
 * без мессенджера вообще: секунда — и конец.
 *
 * Поэтому камеру рисуем сами. Всё остальное — захват, отдача, раздача,
 * приём — остаётся тем же, каким его видит человек; подменён только
 * источник кадров, и подменён на такой, который не умирает.
 *
 * Микрофон не трогаем: поддельный звук работает исправно.
 */
const родной = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);

navigator.mediaDevices.getUserMedia = async function (ограничения = {}) {
  if (!ограничения.video) return родной(ограничения);

  const холст = document.createElement("canvas");
  холст.width = 640;
  холст.height = 360;
  const кисть = холст.getContext("2d", { alpha: false });

  let кадр = 0;
  setInterval(() => {
    кадр += 1;
    кисть.fillStyle = "#122";
    кисть.fillRect(0, 0, 640, 360);
    кисть.fillStyle = `hsl(${кадр % 360} 70% 55%)`;
    кисть.fillRect((кадр * 6) % 560, 120 + Math.sin(кадр / 8) * 60, 80, 80);
  }, 1000 / 30);

  const поток = холст.captureStream(30);

  if (ограничения.audio) {
    const звук = await родной({ audio: ограничения.audio });
    for (const дорожка of звук.getAudioTracks()) поток.addTrack(дорожка);
  }

  return поток;
};
