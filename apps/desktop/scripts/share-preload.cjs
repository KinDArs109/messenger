// Подпорки для сквозной проверки звука показа (check-share-sound.cjs).
//
// Обе — про окружение проверки, а не про мессенджер: подменён только
// источник картинки и звука, весь путь мессенджера остаётся своим.

/*
 * 1. Своя камера вместо поддельной.
 *
 * Поддельная камера Chromium живёт здесь ровно секунду: дорожка сама
 * уходит в ended, и мессенджер честно прекращает показ — для него это
 * «камеру выдернули». Поэтому рисуем сами. Микрофон не трогаем:
 * поддельный звук работает исправно, и его писк на 440 Гц проверке
 * даже полезен — он показывает, что меряем мы не вообще громкость,
 * а именно тон показа.
 */
const родной = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);

function холстСКартинкой() {
  const холст = document.createElement("canvas");
  холст.width = 640;
  холст.height = 360;
  const кисть = холст.getContext("2d", { alpha: false });

  let кадр = 0;
  setInterval(() => {
    кадр += 1;
    кисть.fillStyle = "#122";
    кисть.fillRect(0, 0, 640, 360);
    кисть.fillStyle = `hsl(${кадр % 360} 70% 55%)`;
    кисть.fillRect((кадр * 6) % 560, 120 + Math.sin(кадр / 8) * 60, 80, 80);
  }, 1000 / 30);

  return холст.captureStream(30);
}

navigator.mediaDevices.getUserMedia = async function (ограничения = {}) {
  if (!ограничения.video) return родной(ограничения);

  const поток = холстСКартинкой();
  if (ограничения.audio) {
    const звук = await родной({ audio: ограничения.audio });
    for (const дорожка of звук.getAudioTracks()) поток.addTrack(дорожка);
  }
  return поток;
};

/*
 * 2. Свой экран вместо настоящего.
 *
 * Настоящий захват здесь не нужен и вреден: на машине с проверкой
 * может не быть ни второго экрана, ни звука вообще, а окно выбора
 * рисует оболочка, которой в этой проверке нет.
 *
 * Звук показа — ровный тон на 1500 Гц. Частота выбрана подальше от
 * писка поддельных микрофонов (440 Гц): на той стороне проверка
 * смотрит именно на эту полосу и не может спутать показ с голосами.
 */
navigator.mediaDevices.getDisplayMedia = async function () {
  const поток = холстСКартинкой();

  const ctx = new AudioContext();
  const осц = ctx.createOscillator();
  осц.frequency.value = 1500;
  const выход = ctx.createMediaStreamDestination();
  осц.connect(выход);
  осц.start();

  // Держим ссылку: без неё сборщик мусора вправе прибрать и контекст,
  // и генератор — тон замолчит на середине проверки.
  window.__тон = { ctx, осц, выход };

  поток.addTrack(выход.stream.getAudioTracks()[0]);
  return поток;
};
