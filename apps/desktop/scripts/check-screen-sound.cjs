// Проверка: звук чужого показа доходит до наушников.
//
//   npm run check:screen-sound -w @messenger/desktop
//
// Ничего поднимать не надо: ни сервера, ни базы. Проверяется тот
// самый модуль из мессенджера — apps/web/src/lib/screenSound.ts, —
// а не его пересказ.
//
// Почему проверка вообще появилась. Звук показа приезжает отдельной
// дорожкой и почти всегда позже картинки. Через раздачу поток
// собирает сам мессенджер, а addTrack, позванный из своего же кода,
// события addtrack НЕ вызывает — оно только для дорожек, которые
// сложил браузер. На это и опирался прежний код: он ждал события,
// которого в этом случае не бывает. Снаружи выглядело так, что
// картинка идёт, а звука нет и не появится.
//
// Поэтому здесь проверяется не «позвали функцию», а слышимость:
// сигнал ловится на выходе общего усилителя — там же, где его
// услышал бы человек.

const { app, BrowserWindow } = require("electron");
const path = require("node:path");
const esbuild = require("esbuild");

// Без этого AudioContext остаётся спящим, и по графу не идёт ничего:
// проверка меряла бы тишину независимо от того, что чинили.
app.commandLine.appendSwitch("autoplay-policy", "no-user-gesture-required");

const скажи = (строка) => process.stdout.write(`${строка}\n`);

const сторож = setTimeout(() => {
  скажи("\n  ПРОВАЛ: не уложились в минуту\n");
  app.exit(1);
}, 60_000);
сторож.unref?.();

/** Тот же файл, что и в мессенджере, — только собранный в обычный
 *  скрипт: страница TypeScript не понимает. */
function собрать() {
  const где = path.join(__dirname, "..", "..", "web", "src", "lib", "screenSound.ts");
  return esbuild.buildSync({
    entryPoints: [где],
    bundle: true,
    format: "iife",
    globalName: "звук",
    write: false,
    charset: "utf8",
  }).outputFiles[0].text;
}

const сценарий = (модуль) => `
${модуль}
(async () => {
  const итог = [];
  const шаг = (что, вышло, ещё) => итог.push({ что, вышло: Boolean(вышло), ещё });
  const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

  /* ── Наушники: общий усилитель и измеритель на его выходе ───── */
  const ctx = new AudioContext();
  await ctx.resume();
  const master = ctx.createGain();
  const мера = ctx.createAnalyser();
  мера.fftSize = 2048;
  master.connect(мера).connect(ctx.destination);

  /**
   * Громко ли сейчас на выходе.
   *
   * Наибольшее отклонение за отрезок: одного мгновения мало — синус
   * проходит через ноль, и попасть можно ровно в него.
   *
   * Сперва пауза, и она не для красоты. Дорожка приходит в граф
   * через свой буфер, и измеритель отстаёт от происходящего на доли
   * секунды: замерено — сразу после перевода ползунка на четверть
   * измеритель ещё показывает единицу, а четверть появляется только
   * следующим замером. Без паузы проверка мерила бы прошлое.
   */
  async function уровень(осесть = 600, мс = 300) {
    await пауза(осесть);
    const данные = new Float32Array(мера.fftSize);
    let макс = 0;
    const до = performance.now() + мс;
    while (performance.now() < до) {
      мера.getFloatTimeDomainData(данные);
      for (const v of данные) макс = Math.max(макс, Math.abs(v));
      await пауза(20);
    }
    return Math.round(макс * 1000) / 1000;
  }

  const ГРОМКО = 0.2;
  const ТИХО = 0.02;

  /** Звучащая дорожка — вместо чужой игры. */
  function дорожка(громкость = 1) {
    const осц = ctx.createOscillator();
    осц.frequency.value = 440;
    const усил = ctx.createGain();
    усил.gain.value = громкость;
    const выход = ctx.createMediaStreamDestination();
    осц.connect(усил).connect(выход);
    осц.start();
    return выход.stream.getAudioTracks()[0];
  }

  /** Картинка — вместо чужого экрана. */
  function картинка() {
    const холст = document.createElement("canvas");
    холст.width = 320;
    холст.height = 180;
    холст.getContext("2d").fillRect(0, 0, 320, 180);
    return холст.captureStream(5).getVideoTracks()[0];
  }

  const опоры = (громкость = 1) => ({
    context: ctx,
    master,
    черезУсилитель: true,
    громкость: () => громкость,
    вНаушники: async () => {},
  });

  /* ── 1. Как приходит показ через раздачу: сперва картинка,
         звук отдельной дорожкой и позже ─────────────────────── */
  const поток = new MediaStream();
  поток.addTrack(картинка());

  let событие = false;
  поток.addEventListener("addtrack", () => { событие = true; });

  const показ = звук.завестиЗвукПоказа(поток, опоры());
  поток.addTrack(дорожка());
  await пауза(200);

  шаг("свой поток о новой дорожке не сообщает", !событие,
      "на это и опирался прежний код");
  шаг("до проверки звука не слышно", (await уровень()) < ТИХО);

  показ.проверить();
  const слышно = await уровень();
  шаг("после проверки звук показа слышно", слышно > ГРОМКО, слышно);

  /* ── 2. Ползунок показа ─────────────────────────────────────── */
  показ.apply(0.25, 1, false);
  const тише = await уровень();
  шаг("ползунок убавляет", тише < слышно * 0.5 && тише > ТИХО, тише);

  показ.apply(0, 1, false);
  шаг("на нуле — тишина", (await уровень()) < ТИХО);
  показ.apply(1, 1, false);

  /* ── 3. Звук показа сменился, картинка та же ────────────────── */
  for (const т of поток.getAudioTracks()) поток.removeTrack(т);
  поток.addTrack(дорожка(0));
  показ.проверить();
  шаг("прежняя дорожка отключена вместе с заменой", (await уровень()) < ТИХО);

  for (const т of поток.getAudioTracks()) поток.removeTrack(т);
  поток.addTrack(дорожка(1));
  показ.проверить();
  const снова = await уровень();
  шаг("новую дорожку подхватывает", снова > ГРОМКО, снова);

  /* ── 4. Показ кончился ──────────────────────────────────────── */
  показ.stop();
  шаг("после конца показа тишина", (await уровень()) < ТИХО);

  /* ── 5. Прямой путь: поток приходит уже со звуком ────────────── */
  const сразу = new MediaStream([картинка(), дорожка()]);
  const второй = звук.завестиЗвукПоказа(сразу, опоры());
  const сходу = await уровень();
  шаг("готовый поток звучит без напоминаний", сходу > ГРОМКО, сходу);
  второй.stop();

  /* ── 6. Запасной путь: звук идёт элементом, мимо усилителя ──── */
  const мимо = new MediaStream([картинка(), дорожка()]);
  let вНаушникиЗвали = false;
  const третий = звук.завестиЗвукПоказа(мимо, {
    context: ctx,
    master,
    черезУсилитель: false,
    громкость: () => 1,
    вНаушники: async () => { вНаушникиЗвали = true; },
  });
  третий.проверить();
  шаг("мимо усилителя ничего не подмешивается", (await уровень()) < ТИХО);
  шаг("и наушники выбираются на самом элементе", вНаушникиЗвали);
  третий.stop();

  return итог;
})();
`;

void app.whenReady().then(async () => {
  const окно = new BrowserWindow({
    show: false,
    webPreferences: { backgroundThrottling: false, sandbox: true },
  });

  await окно.loadURL("about:blank");

  let итог;
  try {
    итог = await окно.webContents.executeJavaScript(сценарий(собрать()), true);
  } catch (беда) {
    скажи(`\n  ПРОВАЛ: проверка не отработала — ${беда.message}\n`);
    app.exit(1);
    return;
  }

  скажи("\nЗвук чужого показа\n");
  let провалов = 0;
  for (const { что, вышло, ещё } of итог) {
    if (!вышло) провалов += 1;
    скажи(`${вышло ? "  ✔" : "  ✘ ПРОВАЛ"} ${что}${ещё === undefined ? "" : ` (${ещё})`}`);
  }

  скажи(
    провалов === 0
      ? `\nЗвук показа доходит до наушников — проверок ${итог.length}\n`
      : `\nПровалов: ${провалов} из ${итог.length}\n`,
  );

  app.exit(провалов === 0 ? 0 : 1);
});
