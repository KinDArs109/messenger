// Что этот компьютер вытягивает на показе экрана.
//
//   npx electron scripts/check-share.cjs
//
// «Плохое качество и мало кадров» — жалоба, у которой три разных
// причины: слабый потолок битрейта, кодировщик без ускорения и
// подсказка кодировщику, которой у нас не было вовсе. Гадать тут
// нельзя: цена ошибки — вечер, потраченный на кручение ручек вслепую.
//
// Поэтому здесь замер. Картинка берётся не с экрана, а рисуется:
// показ идёт с чужой машины, а мерить надо кодировщик, и ему всё
// равно, откуда кадры. Зато рисованная картинка одинакова от прогона
// к прогону — с настоящим экраном, который то замер, то мелькает,
// сравнивать замеры было бы не с чем.
//
// Соединения настоящие: столько же, сколько собеседников. В сети
// «каждый с каждым» картинка кодируется отдельно для каждого, и
// именно это чаще всего и упирается в потолок.

const { app, BrowserWindow } = require("electron");
const path = require("node:path");
const fs = require("node:fs");

const скажи = (строка) => process.stdout.write(`${строка}\n`);

app.commandLine.appendSwitch("enable-features", "WebRTC-H264WithOpenH264FFmpeg");

const сторож = setTimeout(() => {
  скажи("\n  ПРОВАЛ: не уложились в пять минут\n");
  app.exit(1);
}, 300_000);
сторож.unref?.();

void app.whenReady().then(async () => {
  const окно = new BrowserWindow({
    show: false,
    webPreferences: {
      // Скрытое окно браузер придерживает: кадры перестают рисоваться,
      // и замер получился бы про засыпание, а не про кодировщик.
      backgroundThrottling: false,
      sandbox: true,
    },
  });

  // WebRTC живёт только в безопасном источнике; about:blank им
  // не считается. Своя же страница здоровья подходит и ничего
  // не тянет за собой.
  await окно.loadURL(`${process.env.CHECK_URL ?? "https://45.130.42.77.sslip.io"}/health`);

  const сценарий = fs.readFileSync(path.join(__dirname, "share-scenario.js"), "utf8");

  let замеры;
  try {
    замеры = await окно.webContents.executeJavaScript(сценарий, true);
  } catch (беда) {
    скажи(`\n  ПРОВАЛ: замер не отработал — ${беда.message}\n`);
    app.exit(1);
    return;
  }

  скажи("\nЧто вытягивает этот компьютер на показе экрана\n");
  скажи("  собеседников: 3, как в разговоре вчетвером\n");

  const шапка = ["настройка", "кадры", "размер", "на одного", "чёткость QP", "упёрлось в"];
  const строки = замеры.map((з) => [
    з.имя,
    з.ошибка ? "—" : `${з.fps} к/с`,
    з.ошибка ? "—" : `${з.width}×${з.height}`,
    з.ошибка ? "—" : `${з.мбит} Мбит/с`,
    з.ошибка ? "—" : String(з.qp),
    з.ошибка ?? з.предел ?? "ни во что",
  ]);

  const ширины = шапка.map((_, i) =>
    Math.max(шапка[i].length, ...строки.map((с) => String(с[i]).length)),
  );
  const строка = (ячейки) =>
    "  " + ячейки.map((я, i) => String(я).padEnd(ширины[i])).join("  ");

  скажи(строка(шапка));
  скажи("  " + ширины.map((ш) => "─".repeat(ш)).join("  "));
  for (const с of строки) скажи(строка(с));
  скажи("");

  app.exit(0);
});
