// Проверка правила «держать кадры, жертвуя размером».
//
//   npm run check:adapt -w @messenger/web
//
// Когда кодировщику тесно, он режет и размер, и кадры сразу — и выходит
// худшее из двух: мыло, которое ещё и дёргается. Мессенджер отбирает
// у него этот выбор: сам отдаёт картинку поменьше, чтобы на кадры
// хватило.
//
// Правило простое на словах и легко ломается на деле: то показ прыгает
// между размерами на каждой просадке, то, опустившись, застревает внизу
// навсегда. Глазом это ловится только на живом разговоре с игрой в фоне
// и через минуту после ошибки; здесь — за секунду.

import {
  высотаСтупени,
  решить,
  НАЧАЛО,
  СТУПЕНИ,
  ПЛОХИХ_ПОДРЯД,
  ХОРОШИХ_ПОДРЯД,
  type Положение,
} from "../src/lib/adapt.js";

let провалов = 0;
const ok = (s: string) => console.log(`  ✔ ${s}`);
const fail = (s: string) => {
  console.log(`  ✘ ПРОВАЛ: ${s}`);
  провалов += 1;
};

const ЦЕЛЬ = 60;

/** Прогнать череду замеров и вернуть, на какой ступени оказались. */
function прогнать(было: Положение, кадры: (number | null)[]): Положение {
  let сейчас = было;
  for (const fps of кадры) сейчас = решить(сейчас, fps, ЦЕЛЬ);
  return сейчас;
}

const повтор = (сколько: number, что: number | null) => Array.from({ length: сколько }, () => что);

console.log("\nПоказ подстраивается сам\n");

console.log("=== Когда опускаться ===");

{
  const после = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД - 1, 20));
  if (после.шаг === 0) ok("одна просадка показ не трогает");
  else fail(`опустились раньше времени: шаг ${после.шаг}`);
}

{
  const после = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, 20));
  if (после.шаг === 1) ok("три подряд — опускаемся на ступень");
  else fail(`после трёх плохих шаг ${после.шаг}, ожидался 1`);
}

{
  // Просадка, потом всё хорошо, потом снова просадка — это не «плохо
  // подряд», и опускаться не за что.
  const после = прогнать(НАЧАЛО, [20, 60, 20, 60, 20, 60]);
  if (после.шаг === 0) ok("рябь через хорошие замеры не считается");
  else fail(`шаг ${после.шаг} на ряби`);
}

{
  const после = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД * 10, 5));
  if (после.шаг === СТУПЕНИ.length - 1) ok("ниже последней ступени не опускаемся");
  else fail(`шаг ${после.шаг}, а ступеней ${СТУПЕНИ.length}`);
}

console.log("\n=== Когда возвращаться ===");

{
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, 20));
  const после = прогнать(внизу, повтор(ХОРОШИХ_ПОДРЯД - 1, 60));
  if (после.шаг === 1) ok("несколько хороших замеров наверх не поднимают");
  else fail(`поднялись рано: шаг ${после.шаг}`);
}

{
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, 20));
  const после = прогнать(внизу, повтор(ХОРОШИХ_ПОДРЯД, 60));
  if (после.шаг === 0) ok("двадцать секунд спокойствия — возвращаемся");
  else fail(`не вернулись: шаг ${после.шаг}`);
}

{
  // Между «плохо» и «хорошо» намеренная пустота: у самой границы
  // не двигаемся никуда, иначе показ дрожал бы на ровном месте.
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, 20));
  const после = прогнать(внизу, повтор(ХОРОШИХ_ПОДРЯД * 3, ЦЕЛЬ * 0.8));
  if (после.шаг === 1) ok("на границе не дёргаемся ни вверх, ни вниз");
  else fail(`сдвинулись на границе: шаг ${после.шаг}`);
}

{
  // Череда «хорошо-плохо-хорошо» не должна поднимать: счётчик
  // спокойствия сбрасывается.
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, 20));
  const рябь: number[] = [];
  for (let i = 0; i < ХОРОШИХ_ПОДРЯД * 2; i += 1) рябь.push(i % 3 === 2 ? 20 : 60);
  const после = прогнать(внизу, рябь);
  if (после.шаг >= 1) ok("при ряби наверх не возвращаемся");
  else fail("вернулись наверх, хотя кадры продолжают проседать");
}

console.log("\n=== Мелочи, на которых легко ошибиться ===");

{
  const после = прогнать(НАЧАЛО, повтор(10, null));
  if (после.шаг === 0) ok("пока кадров не знаем, ничего не решаем");
  else fail("опустились, не зная кадров");
}

{
  const после = решить(НАЧАЛО, 0, 0);
  if (после.шаг === 0) ok("нулевая цель не делит на ноль");
  else fail("сломались на нулевой цели");
}

{
  const высоты = СТУПЕНИ.map((_, шаг) => высотаСтупени(1080, шаг));
  const чётные = высоты.every((в) => в % 2 === 0);
  const убывают = высоты.every((в, i) => i === 0 || в < высоты[i - 1]!);
  if (высоты[0] === 1080 && чётные && убывают) ok(`ступени: ${высоты.join(" → ")}`);
  else fail(`ступени вышли странные: ${высоты.join(" → ")}`);
}

{
  // Ступень считается от того, что выбрал человек, а не от 1080:
  // у выбравшего 720p показ должен опускаться от 720.
  const от720 = высотаСтупени(720, 1);
  if (от720 < 720 && от720 > 400) ok(`от 720p опускаемся до ${от720}p, а не до чужой цифры`);
  else fail(`от 720p получили ${от720}p`);
}

console.log(провалов === 0 ? "\nПравило держится\n" : `\nПровалов: ${провалов}\n`);
process.exit(провалов === 0 ? 0 : 1);
