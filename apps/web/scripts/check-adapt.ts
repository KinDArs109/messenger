// Проверка правила «держать кадры, жертвуя размером».
//
//   npm run check:adapt -w @messenger/web
//
// Когда кодировщику тесно, он режет и размер, и кадры сразу — и выходит
// худшее из двух: мыло, которое ещё и дёргается. Мессенджер отбирает
// у него этот выбор: сам отдаёт картинку поменьше, чтобы на кадры
// хватило.
//
// Главное, что здесь проверяется, — что он не делает этого зря.
// Первая версия правила смотрела только на кадры и опускала показ на
// спокойном экране: у показа экрана кадров мало не потому, что не
// тянет, а потому, что ничего не движется. Через минуту разговора
// картинка оказывалась в 540p без всякой причины — и это выглядело
// ровно как «качество плохое».

import {
  высотаСтупени,
  решить,
  НАЧАЛО,
  СТУПЕНИ,
  ПЛОХИХ_ПОДРЯД,
  ХОРОШИХ_ПОДРЯД,
  type Положение,
  type Замер,
} from "../src/lib/adapt.js";

let провалов = 0;
const ok = (s: string) => console.log(`  ✔ ${s}`);
const fail = (s: string) => {
  console.log(`  ✘ ПРОВАЛ: ${s}`);
  провалов += 1;
};

const ЦЕЛЬ = 60;

/** Прогнать череду замеров и вернуть, на какой ступени оказались. */
function прогнать(было: Положение, замеры: Замер[]): Положение {
  let сейчас = было;
  for (const замер of замеры) сейчас = решить(сейчас, замер, ЦЕЛЬ);
  return сейчас;
}

const повтор = (сколько: number, замер: Замер) => Array.from({ length: сколько }, () => замер);

/** Кодировщику тесно и кадров мало — то самое, ради чего правило есть. */
const тесно: Замер = { fps: 20, предел: "cpu" };
/** Всё хорошо: кадры идут, кодировщик молчит. */
const вольно: Замер = { fps: 60, предел: null };
/** Спокойный экран: кадров мало, но кодировщик ни во что не упёрся. */
const тишина: Замер = { fps: 4, предел: null };

console.log("\nПоказ подстраивается сам\n");

console.log("=== Когда опускаться ===");

{
  const после = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД - 1, тесно));
  if (после.шаг === 0) ok("одна просадка показ не трогает");
  else fail(`опустились раньше времени: шаг ${после.шаг}`);
}

{
  const после = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, тесно));
  if (после.шаг === 1) ok("три раза подряд тесно — опускаемся на ступень");
  else fail(`после трёх тесных шаг ${после.шаг}, ожидался 1`);
}

{
  const после = прогнать(НАЧАЛО, [тесно, вольно, тесно, вольно, тесно, вольно]);
  if (после.шаг === 0) ok("рябь через свободные замеры не считается");
  else fail(`шаг ${после.шаг} на ряби`);
}

{
  const после = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД * 10, тесно));
  if (после.шаг === СТУПЕНИ.length - 1) ok("ниже последней ступени не опускаемся");
  else fail(`шаг ${после.шаг}, а ступеней ${СТУПЕНИ.length}`);
}

console.log("\n=== Спокойный экран трогать нельзя ===");

{
  // Главный случай. Человек показывает не игру, а меню или окно
  // с текстом: кадров пять в секунду, и это нормально.
  const после = прогнать(НАЧАЛО, повтор(60, тишина));
  if (после.шаг === 0) ok("на спокойном экране показ не опускается вовсе");
  else fail(`опустили спокойный экран до ступени ${после.шаг} — картинка испортится зря`);
}

{
  // И даже если до этого опустились по делу — тишина возвращает наверх.
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, тесно));
  const после = прогнать(внизу, повтор(ХОРОШИХ_ПОДРЯД, тишина));
  if (после.шаг === 0) ok("и возвращает наверх, когда стало свободно");
  else fail(`остались внизу: шаг ${после.шаг}`);
}

{
  // Кодировщику тесно, но кадры идут: он просто держит битрейт.
  // Это не повод портить размер.
  const после = прогнать(НАЧАЛО, повтор(20, { fps: 58, предел: "bandwidth" }));
  if (после.шаг === 0) ok("тесно, но кадры идут — размер не трогаем");
  else fail(`опустились при живых кадрах: шаг ${после.шаг}`);
}

console.log("\n=== Когда возвращаться ===");

{
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, тесно));
  const после = прогнать(внизу, повтор(ХОРОШИХ_ПОДРЯД - 1, вольно));
  if (после.шаг === 1) ok("несколько свободных замеров наверх не поднимают");
  else fail(`поднялись рано: шаг ${после.шаг}`);
}

{
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, тесно));
  const после = прогнать(внизу, повтор(ХОРОШИХ_ПОДРЯД, вольно));
  if (после.шаг === 0) ok("двадцать секунд свободы — возвращаемся");
  else fail(`не вернулись: шаг ${после.шаг}`);
}

{
  const внизу = прогнать(НАЧАЛО, повтор(ПЛОХИХ_ПОДРЯД, тесно));
  const рябь: Замер[] = [];
  for (let i = 0; i < ХОРОШИХ_ПОДРЯД * 2; i += 1) рябь.push(i % 3 === 2 ? тесно : вольно);
  const после = прогнать(внизу, рябь);
  if (после.шаг >= 1) ok("при ряби наверх не возвращаемся");
  else fail("вернулись наверх, хотя кодировщику всё ещё тесно");
}

console.log("\n=== Мелочи, на которых легко ошибиться ===");

{
  const после = прогнать(НАЧАЛО, повтор(10, { fps: null, предел: null }));
  if (после.шаг === 0) ok("пока кадров не знаем, ничего не решаем");
  else fail("опустились, не зная кадров");
}

{
  const после = решить(НАЧАЛО, { fps: 0, предел: "cpu" }, 0);
  if (после.шаг === 0) ok("нулевая цель не делит на ноль");
  else fail("сломались на нулевой цели");
}

{
  const высоты = СТУПЕНИ.map((_, шаг) => высотаСтупени(1080, шаг));
  const чётные = высоты.every((в) => в % 2 === 0);
  const убывают = высоты.every((в, i) => i === 0 || в < высоты[i - 1]!);
  if (высоты[0] === 1080 && чётные && убывают) ok(`ступени: ${высоты.join(" → ")}`);
  else fail(`ступени вышли странные: ${высоты.join(" → ")}`);
}

{
  const от720 = высотаСтупени(720, 1);
  if (от720 < 720 && от720 > 400) ok(`от 720p опускаемся до ${от720}p, а не до чужой цифры`);
  else fail(`от 720p получили ${от720}p`);
}

console.log(провалов === 0 ? "\nПравило держится\n" : `\nПровалов: ${провалов}\n`);
process.exit(провалов === 0 ? 0 : 1);
