// Проверка огонька «говорит».
//
//   npm run check:speaking -w @messenger/web
//
// Проверяется ровно то, на что жаловались: «говоришь — начинает
// мигать». Мигание не видно ни в типах, ни в вёрстке, и поймать его
// можно только на подвижном сигнале — поэтому речь тут собирается
// искусственно, зато с настоящей её особенностью: паузами между
// слогами, на которых громкость проваливается почти до нуля.

import { SpeechGate } from "../src/lib/speaking.js";

let failed = false;
const ok = (s: string) => console.log(`  ✔ ${s}`);
const fail = (s: string) => {
  console.log(`  ✘ ПРОВАЛ: ${s}`);
  failed = true;
};

/** Замеры идут каждые 80 мс — так же, как в звуковом слое. */
const TICK = 80;

/** Прогнать последовательность громкостей и посчитать, сколько раз
 *  огонёк переключился. Мигание — это и есть лишние переключения. */
function прогнать(уровни: number[]): { переключений: number; конец: boolean; горелоТиков: number } {
  const gate = new SpeechGate();
  let prev = false;
  let переключений = 0;
  let горелоТиков = 0;

  уровни.forEach((rms, i) => {
    const speaking = gate.feed(rms, i * TICK);
    if (speaking !== prev) переключений++;
    if (speaking) горелоТиков++;
    prev = speaking;
  });

  return { переключений, конец: prev, горелоТиков };
}

/** Речь: слог звучит, потом пауза, и так далее. Паузы настоящие —
 *  между слогами громкость падает практически в тишину. */
function речь(слогов: number): number[] {
  const out: number[] = [];
  for (let i = 0; i < слогов; i++) {
    for (let t = 0; t < 2; t++) out.push(0.14); // ~160 мс звука
    for (let t = 0; t < 2; t++) out.push(0.004); // ~160 мс паузы
  }
  return out;
}

const тишина = (тиков: number) => Array.from({ length: тиков }, () => 0.002);

console.log("\nОгонёк «говорит»\n");

console.log("=== Тишина ===");
{
  const r = прогнать(тишина(50));
  r.переключений === 0 && !r.конец
    ? ok("молчит — огонёк не загорается ни разу")
    : fail(`огонёк дёрнулся ${r.переключений} раз на тишине`);
}

console.log("\n=== Речь с паузами между слогами ===");
{
  const r = прогнать(речь(12));
  // Одно переключение — это «загорелся». Всё, что сверх, — мигание.
  if (r.переключений === 1 && r.конец) ok("загорелся один раз и не мигал все 12 слогов");
  else if (r.переключений > 1) fail(`огонёк переключился ${r.переключений} раз — это мигание`);
  else fail("огонёк так и не загорелся на речи");
}

console.log("\n=== Замолчал ===");
{
  const r = прогнать([...речь(6), ...тишина(20)]);
  if (r.конец) fail("огонёк остался гореть после того, как человек замолчал");
  else if (r.переключений !== 2) fail(`ожидалось загорелся-погас, а переключений ${r.переключений}`);
  else ok("после речи погас, и ровно один раз");
}

console.log("\n=== Одиночный щелчок ===");
{
  // Стук по столу, щелчок мыши — один громкий замер и снова тишина.
  const r = прогнать([...тишина(10), 0.2, ...тишина(30)]);
  r.переключений === 0
    ? ok("короткий щелчок за речь не принят")
    : fail("огонёк загорелся от одиночного щелчка");
}

console.log("\n=== Пауза между фразами ===");
{
  // Полсекунды тишины — это уже «договорил», огонёк обязан погаснуть
  // и загореться заново на следующей фразе.
  const r = прогнать([...речь(4), ...тишина(8), ...речь(4)]);
  // Загорелся, погас, загорелся снова — три перехода, а не четыре:
  // огонёк начинает с погашенного.
  r.переключений === 3
    ? ok("на паузе в полсекунды погас и снова загорелся")
    : fail(`ожидалось 3 перехода на двух фразах, получено ${r.переключений}`);
}

console.log("\n=== Тихий голос ===");
{
  // То, на что жаловались: человек говорит спокойно, уровень впятеро
  // ниже обычного. Для жёсткого порога это была тишина.
  const тихо = (слогов: number) => {
    const out: number[] = [];
    for (let i = 0; i < слогов; i++) {
      for (let t = 0; t < 2; t++) out.push(0.018);
      for (let t = 0; t < 2; t++) out.push(0.002);
    }
    return out;
  };
  const r = прогнать([...тишина(20), ...тихо(10)]);
  if (!r.конец) fail("тихий голос огонёк не зажёг");
  else if (r.переключений > 1) fail(`на тихом голосе огонёк мигал: ${r.переключений} переключений`);
  else ok("тихий голос зажигает огонёк и не мигает");
}

console.log("\n=== Шумная комната ===");
{
  // Фон громкий сам по себе — вентилятор, улица. Он не должен зажигать
  // огонёк, а голос поверх него — должен.
  const шум = (тиков: number) => Array.from({ length: тиков }, () => 0.03 + Math.random() * 0.004);
  const громко = (слогов: number) => {
    const out: number[] = [];
    for (let i = 0; i < слогов; i++) {
      for (let t = 0; t < 2; t++) out.push(0.16);
      for (let t = 0; t < 2; t++) out.push(0.032);
    }
    return out;
  };
  const один = прогнать(шум(60));
  один.переключений === 0
    ? ok("сам по себе шум огонёк не зажигает")
    : fail(`шум зажёг огонёк ${один.переключений} раз`);

  const два = прогнать([...шум(40), ...громко(8)]);
  два.конец ? ok("голос поверх шума зажигает") : fail("в шумной комнате голос огонёк не зажёг");
}

console.log(failed ? "\nЕсть провалы\n" : "\nВсё сходится\n");
process.exit(failed ? 1 : 0);
