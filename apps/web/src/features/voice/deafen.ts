/**
 * Что делать с микрофоном, когда включают или выключают звук.
 *
 * Отдельно от кнопки и от хранилища, потому что это не про интерфейс,
 * а про правило — и правило с памятью: чтобы вернуть микрофон, надо
 * помнить, кто его выключил.
 *
 * Выключение звука гасит и микрофон: не слышать собеседников и
 * продолжать им говорить — почти всегда ошибка. Но раньше выключение
 * было с последствиями, а включение без: звук возвращался, микрофон
 * оставался выключенным, и человек говорил в пустоту, пока ему
 * об этом не скажут.
 *
 * Обратно включаем не всегда, а только свой же выключенный микрофон.
 * Тот, кто выключил его сам ещё до этого, включать не просил, и
 * «вернуть как было» для него значит оставить выключенным.
 */

export interface MicDecision {
  muted: boolean;
  /** Выключен нами вместе со звуком, а не человеком. */
  mutedByDeafen: boolean;
}

export function micOnDeafenChange(
  /** Каким звук становится. */
  deafened: boolean,
  /** Микрофон сейчас. */
  muted: boolean,
  /** Кто его выключил: мы вместе со звуком или человек сам. */
  mutedByDeafen: boolean,
): MicDecision | null {
  if (deafened) {
    // Уже молчит — значит человек так решил сам. Метку не ставим:
    // иначе при возврате звука мы включили бы микрофон за него.
    if (muted) return null;
    return { muted: true, mutedByDeafen: true };
  }

  // Не наших рук дело — не наше и возвращать.
  if (!mutedByDeafen) return null;
  return { muted: false, mutedByDeafen: false };
}
