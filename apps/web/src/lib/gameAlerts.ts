/**
 * «Ваня запустил Rust» — когда стоит сказать, а когда промолчать.
 *
 * Ради этого мессенджер, в общем, и собирали: узнать, что друзья
 * садятся играть, раньше можно было только спросив. «Играет в …»
 * в списке друзей отвечает на этот вопрос, но только если туда
 * смотреть, — а смотрят туда как раз тогда, когда уже вспомнили.
 *
 * Правило вынесено отдельно от всего остального намеренно: это
 * единственное место, где решается, будить человека или нет, и его
 * надо уметь проверить числами, а не «кажется, работает». Проверка —
 * scripts/check-game-alerts.mjs.
 */

export interface AlertContext {
  /** Кто запустил. Своё запускание не новость. */
  userId: string;
  /** Кто мы. */
  meId: string | null;
  /** Что запустил. null — наоборот, закрыл игру. */
  game: string | null;
  /** Во что играли мы сами за последнее время. */
  myGames: string[];
  /** Хочет ли человек такие уведомления вообще. */
  enabled: boolean;
  /** Сидим ли мы уже в разговоре: значит, и так вместе. */
  inCall: boolean;
  /** Просил не беспокоить. */
  quiet: boolean;
  /** Уже говорили про эту игру у этого человека — не повторяемся.
   *  Игра иногда «перезапускается» сама: вылетела, поднялась заново,
   *  сменила процесс на лаунчер и обратно. */
  told: boolean;
}

/** Сравниваем имена без оглядки на регистр и лишние пробелы:
 *  «Rust» из списка известных и «rust» из чужой настройки — одна игра. */
const ключ = (game: string): string => game.trim().toLowerCase();

export function shouldAlertGame(context: AlertContext): boolean {
  const { userId, meId, game, myGames, enabled, inCall, quiet, told } = context;

  if (!enabled || quiet) return false;
  // Закрыл игру — не новость.
  if (!game) return false;
  // Себя не поздравляем.
  if (!meId || userId === meId) return false;
  // Уже в разговоре — значит, уже вместе, и рассказывать нечего.
  if (inCall) return false;
  if (told) return false;

  // Только то, во что играем и мы. Иначе уведомление приходит
  // на каждую чужую игру, включая ту, которую мы никогда не ставили, —
  // и через неделю его выключают вместе со всеми остальными.
  return myGames.map(ключ).includes(ключ(game));
}

/**
 * Запомнить свою игру.
 *
 * Список короткий и сам себя чистит: держим последние десять. Человек
 * ничего не настраивает — мессенджер и так видит, во что он играл,
 * и именно это делает уведомление уместным: «запустил то, во что
 * играешь ты» вместо «запустил хоть что-нибудь».
 */
export function rememberGame(mine: string[], game: string | null): string[] {
  if (!game) return mine;
  const было = mine.filter((name) => ключ(name) !== ключ(game));
  return [game, ...было].slice(0, 10);
}
