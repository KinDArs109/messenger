/**
 * Выбор кодека для показа экрана.
 *
 * Отдельным файлом, потому что от этой дюжины строк зависит, увидят
 * ли собеседники экран или мыло: браузер, предоставленный сам себе,
 * берёт для показа VP8 — а VP8 у нас жмёт процессор.
 *
 * Замерено на боевом ноутбуке (apps/desktop/scripts/check-share.cjs:
 * одна и та же движущаяся картинка уходит в три соединения сразу,
 * как в разговоре вчетвером):
 *
 *   VP8,  1080p, 30 к/с, 2,5 Мбит  →  960×540, 15 кадров
 *   H264, 1080p, 30 к/с, 5 Мбит    →  1920×1080, 27 кадров, ни в
 *                                     что не упирается
 *
 * Разница не в настройках, а в том, кто жмёт: H264 умеет видеокарта,
 * VP8 в этой сборке — только процессор, и на трёх соединениях он
 * не справляется. Отсюда и «плохое качество, и фпс маленький» разом:
 * не хватило ни на чёткость, ни на плавность.
 */

/**
 * Попросить H264 для этой дорожки.
 *
 * Именно попросить: переставляем список предпочтений, а договариваются
 * стороны сами. Нет H264 у нас или у собеседника — список останется
 * прежним, и показ пойдёт как раньше, просто хуже.
 *
 * Звать надо до того, как соединение начнёт договариваться: после
 * согласования просьба опоздает и молча ничего не изменит.
 */
export function просимH264(connection: RTCPeerConnection, sender: RTCRtpSender): boolean {
  const умеет = RTCRtpSender.getCapabilities?.("video");
  const transceiver = connection.getTransceivers().find((t) => t.sender === sender);
  if (!умеет || !transceiver?.setCodecPreferences) return false;

  const h264 = умеет.codecs.filter((c) => c.mimeType.toLowerCase() === "video/h264");
  if (h264.length === 0) return false;

  try {
    transceiver.setCodecPreferences([
      ...h264,
      ...умеет.codecs.filter((c) => !h264.includes(c)),
    ]);
    return true;
  } catch {
    // Браузер не дал переставить список — пойдём как раньше.
    return false;
  }
}
