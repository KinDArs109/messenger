/**
 * Когда опускать показ, а когда возвращать обратно.
 *
 * Вынесено отдельно от голосового слоя нарочно: это чистое решение
 * по числам, и проверять его надо числами, а не разговором вчетвером
 * с игрой в фоне. Ошибка здесь не видна глазом сразу — она видна
 * через минуту, когда показ начинает прыгать между размерами или,
 * наоборот, застревает внизу навсегда.
 */

/** Ступени, по которым показ опускается: доли от выбранной высоты.
 *  1080 → 900 → 720 → 540. Ниже не идём — там уже не «хуже видно»,
 *  там не видно. */
export const СТУПЕНИ = [1, 0.83, 0.66, 0.5];

/** Сколько замеров подряд должно быть плохо, прежде чем опустимся.
 *  Замер идёт раз в две секунды; шесть секунд — это уже не рябь,
 *  а положение дел. */
export const ПЛОХИХ_ПОДРЯД = 3;

/** И сколько хороших, чтобы вернуться. Возвращаться надо медленнее,
 *  чем опускаться, иначе показ будет прыгать туда-сюда на каждом
 *  чихе. Двадцать секунд спокойствия — довод, десять — совпадение. */
export const ХОРОШИХ_ПОДРЯД = 10;

/** Ниже этой доли от цели считаем, что кадров не хватает. */
const ПЛОХО = 0.75;

/** А выше этой — что всё в порядке и можно думать о возвращении.
 *  Между ними намеренная пустота: у самой границы не двигаемся
 *  ни туда, ни сюда. */
const ХОРОШО = 0.9;

export interface Положение {
  /** Насколько ступеней вниз опущен показ. */
  шаг: number;
  /** Сколько замеров подряд плохо. */
  плохих: number;
  /** Сколько замеров подряд хорошо. */
  спокойных: number;
}

export const НАЧАЛО: Положение = { шаг: 0, плохих: 0, спокойных: 0 };

/**
 * Что делать после очередного замера.
 *
 * Возвращает новое положение; если шаг изменился — вызывающему пора
 * трогать захват. Само по себе решение ничего не меняет: это чистая
 * арифметика, и её удобно проверять.
 */
export function решить(было: Положение, fps: number | null, цель: number): Положение {
  // Кадров не знаем — ничего не решаем. Показ мог только начаться,
  // и первые замеры приходят пустыми.
  if (fps === null || цель <= 0) return было;

  if (fps < цель * ПЛОХО) {
    const плохих = было.плохих + 1;
    if (плохих >= ПЛОХИХ_ПОДРЯД && было.шаг < СТУПЕНИ.length - 1) {
      return { шаг: было.шаг + 1, плохих: 0, спокойных: 0 };
    }
    return { шаг: было.шаг, плохих, спокойных: 0 };
  }

  if (fps < цель * ХОРОШО) {
    // Ни туда ни сюда: кадров хватает, но с запасом, которого мало
    // для возвращения наверх.
    return { шаг: было.шаг, плохих: 0, спокойных: 0 };
  }

  if (было.шаг === 0) return { шаг: 0, плохих: 0, спокойных: 0 };

  const спокойных = было.спокойных + 1;
  if (спокойных >= ХОРОШИХ_ПОДРЯД) {
    return { шаг: было.шаг - 1, плохих: 0, спокойных: 0 };
  }
  return { шаг: было.шаг, плохих: 0, спокойных };
}

/**
 * Какую высоту отдавать захвату на этой ступени.
 *
 * Округляем до шестидесяти, а не до чётного: доли дают 896 и 712,
 * и в полосе «опустил показ до 896p» выглядит как ошибка, а не как
 * решение. Кратные шестидесяти дают привычные 900, 720, 540 —
 * и кодировщикам они нравятся не меньше.
 */
export function высотаСтупени(база: number, шаг: number): number {
  if (шаг <= 0) return база;
  const сырое = база * (СТУПЕНИ[шаг] ?? 1);
  return Math.max(240, Math.round(сырое / 60) * 60);
}
