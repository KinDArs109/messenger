/**
 * Когда опускать показ, а когда возвращать обратно.
 *
 * Вынесено отдельно от голосового слоя нарочно: это чистое решение
 * по числам, и проверять его надо числами, а не разговором вчетвером
 * с игрой в фоне. Ошибка здесь не видна глазом сразу — она видна
 * через минуту, когда показ начинает прыгать между размерами или,
 * наоборот, застревает внизу навсегда.
 *
 * Главный урок этого файла оплачен дважды. Первая мысль была простая:
 * мало кадров — опускай размер. Она неверна, и вот почему: у показа
 * экрана кадры считаются не так, как у камеры. Камера отдаёт шестьдесят
 * кадров всегда, даже если человек сидит неподвижно. Экран отдаёт
 * ровно столько, сколько на нём меняется: в меню игры или на спокойном
 * рабочем столе честные пять кадров в секунду — не беда, а тишина.
 *
 * Опускать показ в такие минуты значит портить картинку ровно тогда,
 * когда её проще всего было бы отдать в лучшем виде. Поэтому теперь
 * решает не число кадров, а признание самого кодировщика: «мне тесно».
 * Он его сообщает — процессором или полосой, — и только это считается
 * доводом.
 */

/** Ступени, по которым показ опускается: доли от выбранной высоты.
 *  1080 → 900 → 720 → 540. Ниже не идём — там уже не «хуже видно»,
 *  там не видно. */
export const СТУПЕНИ = [1, 0.83, 0.66, 0.5];

/** Сколько замеров подряд должно быть тесно, прежде чем опустимся.
 *  Замер идёт раз в две секунды; шесть секунд — это уже не рябь,
 *  а положение дел. */
export const ПЛОХИХ_ПОДРЯД = 3;

/** И сколько свободных, чтобы вернуться. Возвращаться надо медленнее,
 *  чем опускаться, иначе показ будет прыгать туда-сюда на каждом
 *  чихе. Двадцать секунд спокойствия — довод, десять — совпадение. */
export const ХОРОШИХ_ПОДРЯД = 10;

/** Ниже этой доли от цели кадров считаем, что их не хватает.
 *  Само по себе это ничего не значит — см. заглавие файла, — но
 *  вместе с «мне тесно» от кодировщика это уже разговор. */
const МАЛО_КАДРОВ = 0.75;

export interface Замер {
  /** Кадров в секунду, которые кодировщик и правда отдал. */
  fps: number | null;
  /** Во что упёрся сам кодировщик. null — ни во что. */
  предел: "cpu" | "bandwidth" | null;
}

export interface Положение {
  /** Насколько ступеней вниз опущен показ. */
  шаг: number;
  /** Сколько замеров подряд тесно. */
  плохих: number;
  /** Сколько замеров подряд свободно. */
  спокойных: number;
}

export const НАЧАЛО: Положение = { шаг: 0, плохих: 0, спокойных: 0 };

/**
 * Что делать после очередного замера.
 *
 * Возвращает новое положение; если шаг изменился — вызывающему пора
 * трогать захват. Само по себе решение ничего не меняет: это чистая
 * арифметика, и её удобно проверять.
 */
export function решить(было: Положение, замер: Замер, цель: number): Положение {
  // Кодировщик молчит — значит, ему хватает. Мало кадров при этом
  // означает лишь, что на экране мало движения.
  if (замер.предел === null) {
    if (было.шаг === 0) return НАЧАЛО;

    const спокойных = было.спокойных + 1;
    if (спокойных >= ХОРОШИХ_ПОДРЯД) return { шаг: было.шаг - 1, плохих: 0, спокойных: 0 };
    return { шаг: было.шаг, плохих: 0, спокойных };
  }

  // Тесно — но опускаемся, только если это видно и по кадрам. Кодировщик
  // говорит «тесно» и тогда, когда просто держит битрейт в рамках, —
  // а картинка при этом идёт как надо.
  const малоКадров = замер.fps !== null && цель > 0 && замер.fps < цель * МАЛО_КАДРОВ;
  if (!малоКадров) return { шаг: было.шаг, плохих: 0, спокойных: 0 };

  const плохих = было.плохих + 1;
  if (плохих >= ПЛОХИХ_ПОДРЯД && было.шаг < СТУПЕНИ.length - 1) {
    return { шаг: было.шаг + 1, плохих: 0, спокойных: 0 };
  }
  return { шаг: было.шаг, плохих, спокойных: 0 };
}

/**
 * Какую высоту отдавать захвату на этой ступени.
 *
 * Округляем до шестидесяти, а не до чётного: доли дают 896 и 712,
 * и в полосе «опустил показ до 896p» выглядит как ошибка, а не как
 * решение. Кратные шестидесяти дают привычные 900, 720, 540 —
 * и кодировщикам они нравятся не меньше.
 */
export function высотаСтупени(база: number, шаг: number): number {
  if (шаг <= 0) return база;
  const сырое = база * (СТУПЕНИ[шаг] ?? 1);
  return Math.max(240, Math.round(сырое / 60) * 60);
}
