/**
 * Решение «человек сейчас говорит».
 *
 * Отдельно от звукового слоя, потому что это не про звук, а про
 * поведение огонька: он должен зажигаться сразу и не мигать.
 *
 * Первая версия сравнивала уровень с одним порогом — и мигала. Причин
 * было две, и обе здесь исправлены.
 *
 * Речь прерывиста. Между слогами и словами уровень проваливается почти
 * до нуля на сотню-другую миллисекунд; с одним порогом огонёк гас
 * на каждой такой паузе. Поэтому здесь два порога и удержание: чтобы
 * зажечься, надо подняться выше верхнего, чтобы погаснуть — опуститься
 * ниже нижнего и продержаться там. Пауза между словами короче
 * удержания и до выключения не доводит.
 *
 * И сам уровень скачет. Поэтому он ещё и сглаживается: одиночный
 * щелчок или всплеск шума не должен считаться словом.
 */

/**
 * Пороги считаются от фона, а не стоят на месте.
 *
 * Раньше они были жёсткими: 0,04 «начал» и 0,02 «замолчал». Для
 * обычного разговора это нормально, а для тихого голоса — нет: человек
 * говорит спокойно, уровень держится около 0,015, и огонёк не
 * загорается вообще. Так и было: «говорю тихо — кружок не работает».
 *
 * Поэтому теперь смотрим, насколько звук громче собственного фона
 * этого микрофона. Тихий голос в тишине — это всё равно втрое громче
 * фона, и он зажигает. Громкий голос в шумной комнате — тоже, потому
 * что планка поднимается вместе с шумом.
 */
/** Во сколько раз громче фона — «начал говорить». */
const RISE_OVER = 3;
/** И ниже какого превышения — «возможно, замолчал». Разрыв между
 *  порогами и есть то, что не даёт дребезжать на границе. */
const FALL_OVER = 1.8;
/** Абсолютный низ. Тише этого не считаем речью ни при каком фоне:
 *  после шумодава фон бывает почти нулевым, и без этой границы
 *  огонёк зажигался бы от шороха самой дорожки. */
const QUIET = 0.006;
/** Сколько держим огонёк после того, как стало тихо. Паузы между
 *  словами укладываются в треть секунды; всё, что дольше, — это уже
 *  «человек замолчал». */
const HOLD_MS = 350;
/** Насколько новый замер влияет на сглаженный уровень. Меньше —
 *  спокойнее, но позже загорается. */
const SMOOTH = 0.65;
/** Сколько замеров подряд должно быть громко, чтобы зажечься.
 *
 *  Два замера — это 160 мс непрерывного звука. Стук по столу, щелчок
 *  мыши, хлопок двери укладываются в один замер и до огонька не
 *  доходят; самый короткий слог — нет.
 *
 *  Считаем по сырому уровню, а не по сглаженному: сглаженный после
 *  громкого щелчка держится высоко ещё пару замеров, и по нему любой
 *  хлопок выглядел бы как два подряд. */
const ATTACK = 2;

/**
 * Фон ищется скользящим минимумом за последние три секунды.
 *
 * Обычное сглаживание тут не годится ни в одну сторону. Быстрое —
 * и длинная фраза сама поднимает планку, человек «замолкает» посреди
 * слова. Медленное — и в шумной комнате планка не успевает подняться
 * вовсе: огонёк загорается от вентилятора и не гаснет никогда.
 *
 * Минимум за окно свободен от обоих: он не может подняться выше самого
 * тихого замера за три секунды, а пауза такой длины есть в любой речи.
 */
const SUB_TICKS = 10;
const WINDOW = 4;

export class SpeechGate {
  private level = 0;
  private speaking = false;
  /** Когда уровень последний раз был выше нижнего порога. */
  private lastLoud = 0;
  /** Сколько сырых замеров подряд были громкими. */
  private loudRun = 0;
  /** Фон этого микрофона: самое тихое за последние секунды. */
  private lowest = Infinity;
  private history = new Array<number>(WINDOW).fill(Infinity);
  private slot = 0;
  private ticks = 0;

  /**
   * Скормить очередной замер громкости (0…1) и получить решение.
   * now — время в миллисекундах, передаётся снаружи, чтобы это
   * можно было проверить без настоящих часов.
   */
  feed(rms: number, now: number): boolean {
    this.level += (rms - this.level) * SMOOTH;

    // Фон ведём по сглаженному уровню: по сырому он ловил бы случайный
    // самый тихий замер и уезжал ниже настоящей тишины.
    if (this.level < this.lowest) this.lowest = this.level;
    this.ticks += 1;
    if (this.ticks >= SUB_TICKS) {
      this.ticks = 0;
      this.history[this.slot] = this.lowest;
      this.slot = (this.slot + 1) % WINDOW;
      this.lowest = Infinity;
    }

    let floor = this.lowest;
    for (const seen of this.history) if (seen < floor) floor = seen;
    if (!isFinite(floor)) floor = this.level;

    const rise = Math.max(QUIET, floor * RISE_OVER);
    const fall = Math.max(QUIET * 0.6, floor * FALL_OVER);

    this.loudRun = rms >= rise ? this.loudRun + 1 : 0;

    if (this.level >= fall) this.lastLoud = now;

    if (this.speaking) {
      // Гаснем, только если тихо уже дольше удержания.
      if (this.level < fall && now - this.lastLoud >= HOLD_MS) this.speaking = false;
    } else if (this.loudRun >= ATTACK) {
      this.speaking = true;
    }

    return this.speaking;
  }
}

/**
 * Громкость по форме волны, а не по спектру.
 *
 * Раньше бралось среднее по всем полосам частот — от нуля до
 * двадцати четырёх килогерц. Голос занимает первые две, а остальные
 * две сотни полос пусты, и полезный сигнал в них растворялся: число
 * получалось и маленьким, и дёрганым. Среднеквадратичное по форме
 * волны — это просто «насколько громко», без оглядки на то, какие
 * там частоты.
 */
export function rmsOf(samples: Uint8Array): number {
  let sum = 0;
  for (const value of samples) {
    // 128 — тишина: значения идут от 0 до 255 вокруг середины.
    const centred = (value - 128) / 128;
    sum += centred * centred;
  }
  return Math.sqrt(sum / samples.length);
}
