/**
 * Звук чужого показа у нас в наушниках.
 *
 * Раньше он играл сам по себе — отдельным элементом мимо общего
 * усилителя. Из-за этого он не подчинялся ни общей громкости,
 * ни «отключить звук», шёл мимо выбранных наушников и, главное,
 * не попадал в опорный сигнал гасителя эха: наш захват экрана ловил
 * чужую игру из динамиков и отправлял её обратно тому, кто её же
 * и показывает. Это и было то самое эхо на демонстрации.
 *
 * Элемент остаётся и на пути через усилитель, но замолкает: без
 * привязки потока к элементу браузер не начинает отдавать по нему
 * данные, и усилитель получает тишину.
 *
 * ── Почему здесь есть «проверить» ───────────────────────────────
 *
 * Звук показа приезжает отдельной дорожкой и почти всегда позже
 * картинки. Значит, собрать усилитель в тот момент, когда показ
 * появился, нельзя: узел-источник берёт дорожки один раз, при
 * создании, и построенный до звука он останется немым навсегда.
 *
 * Раньше второго захода ждали от события addtrack. На прямом пути
 * оно приходит: поток там создаёт браузер, он же и складывает
 * в него приехавшие дорожки. А через раздачу поток собираем мы
 * сами — и addTrack, позванный из мессенджера, события не вызывает:
 * по правилам оно только для дорожек, добавленных браузером.
 * Выходило ровно то, на что жаловались: картинка идёт, а звука нет
 * и не появится.
 *
 * Поэтому вместо события — прямая проверка: тот, кто складывает
 * дорожки, после каждой зовёт «проверить», и усилитель собирается
 * в тот заход, когда звуку и правда есть откуда взяться.
 */

/** Личный усилитель показа. Ссылки держим, чтобы отсоединить. */
interface Узлы {
  gain: GainNode;
  source: MediaStreamAudioSourceNode;
}

export interface ЗвукПоказа {
  stream: MediaStream;
  /** Выставить громкость — тем способом, каким этот звук идёт. */
  apply(personal: number, total: number, deafened: boolean): void;
  /** Перенаправить в другие наушники. Нужно только на запасном пути:
   *  через усилитель устройство меняется у всего разом. */
  reroute(): Promise<void>;
  /** Не приехала ли звуковая дорожка после картинки. Звать после
   *  каждой добавленной в поток дорожки. */
  проверить(): void;
  stop(): void;
}

export interface Опоры {
  context: AudioContext | null;
  master: GainNode | null;
  /** Идёт ли звук через общий усилитель. Нет — значит запасным
   *  путём, прямо элементом. */
  черезУсилитель: boolean;
  /** Громкость именно этого показа: у него свой ползунок. */
  громкость: () => number;
  /** Направить элемент в выбранные наушники. Нужно только
   *  на запасном пути. */
  вНаушники: (audio: HTMLAudioElement) => Promise<void>;
}

export function завестиЗвукПоказа(stream: MediaStream, опоры: Опоры): ЗвукПоказа {
  const { context, master, черезУсилитель, громкость, вНаушники } = опоры;

  const audio = new Audio();
  audio.autoplay = true;
  // На пути через усилитель элемент только «заводит» поток: сам он
  // молчит, иначе звук шёл бы дважды.
  audio.muted = черезУсилитель;
  audio.srcObject = stream;
  if (!черезУсилитель) void вНаушники(audio);

  let узлы: Узлы | null = null;
  /** На какой дорожке собран усилитель. Дорожка может и смениться —
   *  показывающий волен выключить звук и включить его снова, не трогая
   *  картинку, — а узел-источник держит ту, что была при создании. */
  let собранаНа: MediaStreamTrack | null = null;

  const собрать = () => {
    if (!черезУсилитель || !context || !master) return;

    const дорожка = stream.getAudioTracks()[0] ?? null;
    if (!дорожка || дорожка === собранаНа) return;

    узлы?.source.disconnect();
    узлы?.gain.disconnect();

    const source = context.createMediaStreamSource(stream);
    const gain = context.createGain();
    gain.gain.value = громкость();
    source.connect(gain).connect(master);
    узлы = { gain, source };
    собранаНа = дорожка;
  };

  // Событие оставляем: на прямом пути дорожки складывает браузер,
  // и там оно приходит само — раньше, чем нас успеют спросить.
  stream.addEventListener("addtrack", собрать);
  собрать();

  // Со звуком браузер вправе не запускать воспроизведение сам.
  // Тогда ждём любого нажатия по странице: оно даёт то самое
  // разрешение, и звук появляется без единого вопроса человеку.
  let потом: (() => void) | null = null;
  void audio.play().catch(() => {
    потом = () => {
      void audio.play().then(() => document.removeEventListener("click", потом!));
    };
    document.addEventListener("click", потом);
  });

  return {
    stream,
    проверить: собрать,
    apply(personal, total, deafened) {
      if (узлы) {
        узлы.gain.gain.value = personal;
        return;
      }
      // Запасной путь: у элемента громкость только до единицы,
      // поэтому усиление сверх ста процентов здесь недоступно.
      if (черезУсилитель) return;
      audio.volume = Math.min(1, personal * total);
      audio.muted = deafened;
    },
    reroute: () => (черезУсилитель ? Promise.resolve() : вНаушники(audio)),
    stop() {
      stream.removeEventListener("addtrack", собрать);
      if (потом) document.removeEventListener("click", потом);
      узлы?.source.disconnect();
      узлы?.gain.disconnect();
      узлы = null;
      собранаНа = null;
      audio.srcObject = null;
    },
  };
}
