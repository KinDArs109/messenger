// Все проверки одной командой.
//
//   npm run check
//
// Проверок в мессенджере набралось два десятка, и они разные: одни
// считают числа и не требуют ничего, другим нужна поднятая база,
// третьим — работающий сервер. Держать это в голове перед каждой
// выкладкой — верный способ однажды не прогнать ту единственную,
// которая бы всё и поймала.
//
// Поэтому здесь один список. Чего запустить нельзя — пропускается
// вслух, с объяснением: «пропущено, потому что сервер не отвечает»
// куда честнее, чем зелёная строчка, за которой ничего не стояло.
//
// Браузерных проверок здесь нет намеренно: они поднимают по три окна
// Electron и идут минутами. Их зовут отдельно — check:sfu, check:panel,
// check:screens.

import { spawnSync } from "node:child_process";
import path from "node:path";

const КОРЕНЬ = path.join(import.meta.dirname, "..");
const СЕРВЕР = process.env.CHECK_URL ?? "http://127.0.0.1:3001";

const скажи = (строка = "") => process.stdout.write(`${строка}\n`);

/** Проверки, которым ничего не нужно, — чистый счёт. */
const САМИ = [
  ["check:people", "память о людях"],
  ["check:adapt", "показ подстраивается сам"],
  ["check:deafen", "звук и микрофон"],
  ["check:speaking", "кто говорит"],
  ["check:contrast", "читаемость палитры"],
  ["check:amplify", "усилитель голоса"],
  ["check:alerts", "оповещения об играх"],
  ["check:echo", "гаситель эха"],
];

/** Проверки, которым нужна поднятая база. */
const С_БАЗОЙ = [
  ["check:db", "база на месте"],
  ["check:live", "удалённое исчезает у всех"],
];

/** Проверки, которым нужен работающий сервер. */
const С_СЕРВЕРОМ = [
  ["check:realtime", "сокеты: подписки и доставка"],
  ["check:roster", "состав голосового канала"],
  ["check:screen", "объявления о показе"],
  ["check:sfu-server", "раздача картинки"],
  ["check:login", "вход в два шага"],
  ["check:signup", "регистрация"],
  ["check:verify", "почта и доступ"],
  ["check:admin", "хозяйский раздел закрыт", () => Boolean(process.env.CHECK_ADMIN), "не назван CHECK_ADMIN"],
];

function прогнать(имя) {
  // Одной строкой, а не доводами: с оболочкой доводы всё равно
  // склеиваются, и узел за это справедливо ругается.
  const итог = spawnSync(`npm run --silent ${имя}`, {
    cwd: КОРЕНЬ,
    encoding: "utf8",
    shell: true,
    // Проверки бывают долгими, но не бесконечными: висящая проверка
    // не должна подвешивать весь прогон.
    timeout: 180_000,
  });
  return {
    вышло: итог.status === 0,
    вывод: `${итог.stdout ?? ""}${итог.stderr ?? ""}`,
  };
}

/** Отвечает ли сервер и что он о себе говорит. */
async function сервер() {
  try {
    const ответ = await fetch(`${СЕРВЕР}/health`, { signal: AbortSignal.timeout(4000) });
    const тело = await ответ.json();
    return { жив: ответ.ok, ...тело };
  } catch {
    return { жив: false };
  }
}

/** База отвечает — узнаём тем же способом, что и сервер: через него.
 *  Своего подключения здесь нет и не надо. */
const состояние = await сервер();

скажи("\nПроверки мессенджера\n");
скажи(
  состояние.жив
    ? `  сервер отвечает${состояние.раздача === false ? " (раздача не поднята)" : ""}`
    : "  сервер не отвечает — часть проверок будет пропущена",
);
скажи();

const итоги = [];
const прогон = (список, доступно, почему) => {
  for (const [имя, о_чём, нужно, отчего] of список) {
    if (нужно && !нужно()) {
      итоги.push({ имя, о_чём, состояние: "пропущено", почему: отчего });
      скажи(`  ○ ${о_чём} — пропущено: ${отчего}`);
      continue;
    }
    if (!доступно) {
      итоги.push({ имя, о_чём, состояние: "пропущено", почему });
      скажи(`  ○ ${о_чём} — пропущено: ${почему}`);
      continue;
    }
    const { вышло, вывод } = прогнать(имя);
    итоги.push({ имя, о_чём, состояние: вышло ? "прошло" : "провал", вывод });
    скажи(`  ${вышло ? "✔" : "✘ ПРОВАЛ"} ${о_чём}`);
    if (!вышло) {
      // Показываем хвост: в нём всегда стоит, что именно не сошлось.
      for (const строка of вывод.trim().split("\n").slice(-12)) скажи(`      ${строка}`);
    }
  }
};

прогон(САМИ, true);
прогон(С_БАЗОЙ, состояние.жив && состояние.база !== false, "база недоступна");
прогон(С_СЕРВЕРОМ, состояние.жив, "сервер не отвечает");

const провалов = итоги.filter((и) => и.состояние === "провал").length;
const пропущено = итоги.filter((и) => и.состояние === "пропущено").length;
const прошло = итоги.filter((и) => и.состояние === "прошло").length;

скажи();
скажи(
  провалов === 0
    ? `  Всё сходится: прошло ${прошло}${пропущено ? `, пропущено ${пропущено}` : ""}\n`
    : `  Провалов: ${провалов} из ${прошло + провалов}${пропущено ? `, пропущено ${пропущено}` : ""}\n`,
);

process.exit(провалов === 0 ? 0 : 1);
