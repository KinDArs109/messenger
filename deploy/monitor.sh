#!/bin/bash
# Сторож мессенджера: раз в минуту проверяет, что всё живо, и пишет
# в Телеграм, когда что-то сломалось или починилось.
#
# Пишет только на смену состояния, а не каждую минуту: сторож, который
# шлёт «всё хорошо» шестьдесят раз в час, перестают читать через день,
# и настоящую тревогу в этом потоке уже не видно.
#
# Ключ бота лежит отдельно, в monitor.env — сюда его вписывать нельзя,
# этот файл не секретный.
set -uo pipefail

STATE=/var/lib/messenger-monitor
mkdir -p "$STATE"

# Время в сообщениях — по часам того, кто их читает, а не сервера.
# Сервер живёт по UTC, и «лежал с 21:55» означало 00:55 по-нашему:
# три часа разницы человек в полночь пересчитывать не должен.
export TZ=Europe/Moscow

# Сколько раз подряд надо не ответить, чтобы это считалось падением.
# Одного мало: сеть моргает, служба перезапускается за секунды, и
# тревога на каждый такой случай — тот же шум.
LIMIT=2

TELEGRAM_TOKEN=""
TELEGRAM_CHAT=""
# shellcheck disable=SC1091
[ -r /opt/messenger/monitor.env ] && . /opt/messenger/monitor.env

# Проверка связи: --test шлёт пробное сообщение и выходит. Нужна ровно
# один раз, после того как впишете ключ бота, — чтобы убедиться, что
# тревога дойдёт, не дожидаясь настоящего падения.
if [ "${1:-}" = "--test" ]; then
  if [ -z "$TELEGRAM_TOKEN" ] || [ -z "$TELEGRAM_CHAT" ]; then
    [ -z "$TELEGRAM_TOKEN" ] && echo "Не хватает ключа бота в /opt/messenger/monitor.env"
    [ -z "$TELEGRAM_CHAT" ] && echo "Не хватает номера чата в /opt/messenger/monitor.env"
    exit 1
  fi
  answer=$(curl -s -m 20     "https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage"     --data-urlencode "chat_id=${TELEGRAM_CHAT}"     --data-urlencode "text=Проверка связи. Сторож мессенджера на месте — так будет выглядеть тревога.")
  if printf '%s' "$answer" | grep -q '"ok":true'; then
    echo "Отправлено. Проверьте Телеграм."
    exit 0
  fi
  # Ответ Телеграма показываем целиком: в нём написано, что не так —
  # неверный ключ, не тот номер чата или боту ещё не писали.
  echo "Не отправилось. Ответ Телеграма: $answer"
  exit 1
fi

trouble=()

# 1. Отвечает ли сам мессенджер. Не «жив ли процесс»: процесс бывает
#    жив и наглухо занят, а снаружи это то же самое, что мёртв.
body_file="/tmp/health.$$"
code=$(curl -s -m 10 -o "$body_file" -w '%{http_code}' http://127.0.0.1:3001/health 2>/dev/null)
body=$(cat "$body_file" 2>/dev/null)
rm -f "$body_file"
if [ "$code" != "200" ]; then
  trouble+=("мессенджер не отвечает (код $code)")
elif ! printf '%s' "$body" | grep -q '"ok":true'; then
  trouble+=("мессенджер отвечает, но говорит, что ему плохо")
fi

# 2. Снаружи, через веб-сервер и HTTPS. Служба может работать, а Caddy
#    лежать — и для друзей это одно и то же.
#
#    Но «снаружи не открывается» сторож видит и тогда, когда ослеп сам.
#    Так и вышло 17.08.2026: у сервера на час пропало разрешение имён,
#    сторож не смог найти ни сайт, ни Телеграм — и написал «мессенджер
#    не работает». Мессенджер в это время работал: друзья сидели
#    в приложении, а проверка нажатиями прошла целиком через тот же
#    адрес. Тревога, которая кричит о чужой беде, хуже молчания:
#    в следующий раз на неё не придут.
#
#    Поэтому при отказе перепроверяем тот же адрес в обход имён —
#    напрямую по IP. Отвечает — значит сайт жив, а слеп сторож.
outside=$(curl -s -m 15 -o /dev/null -w '%{http_code}' https://45.130.42.77.sslip.io/health 2>/dev/null)
if [ "$outside" != "200" ]; then
  direct=$(curl -s -m 15 --resolve '45.130.42.77.sslip.io:443:45.130.42.77'     -o /dev/null -w '%{http_code}' https://45.130.42.77.sslip.io/health 2>/dev/null)

  if [ "$direct" = "200" ]; then
    # Сайт открывается, не открывается только имя. Это не простой,
    # но и не пустяк: без разрешения имён сервер не достучится
    # до служб уведомлений, и сообщения на телефоны перестанут
    # приходить — молча, что хуже всего.
    trouble+=("у сервера не работает DNS: сайт открывается по адресу, но уведомления на телефон уходить не будут")
  else
    trouble+=("снаружи по HTTPS не открывается (код $outside)")
  fi
fi

# 3. Клиент целиком, а не только страница.
#
#    Страница — это десяток строк, которые ссылаются на скрипт и на
#    оформление. Отдаётся она всегда, даже когда рядом с ней ничего
#    нет: сервер про её содержимое не знает. Поэтому «сайт открывается»
#    и «мессенджером можно пользоваться» — разные вещи.
#
#    Так и вышло при выкладке 20.08.2026: страницу заменили раньше,
#    чем положили рядом новый файл оформления, и минуту мессенджер
#    открывался голой разметкой — списками, огромными картинками,
#    системным шрифтом. Снаружи всё отвечало 200, здоровье было в
#    порядке, сторож молчал.
#
#    Теперь берём то, на что страница ссылается, и проверяем, что оно
#    на месте. Два лишних запроса в минуту — небольшая цена за то,
#    чтобы половинчатая выкладка не жила часами.
page=$(curl -s -m 15 https://45.130.42.77.sslip.io/app 2>/dev/null)
if [ -n "$page" ]; then
  missing=""
  for asset in $(printf '%s' "$page" | grep -o '/assets/[A-Za-z0-9._-]\+' | sort -u); do
    # Смотрим и код, и чем ответили. Одного кода мало: сервер раньше
    # отдавал на несуществующий файл двести и страницу мессенджера —
    # теперь он отвечает честным 404, но проверка на это не полагается.
    answer=$(curl -s -m 15 -o /dev/null -w '%{http_code} %{content_type}' "https://45.130.42.77.sslip.io${asset}" 2>/dev/null)
    case "$asset" in
      *.css) want="text/css" ;;
      *.js)  want="javascript" ;;
      *)     want="" ;;
    esac
    if [ "${answer%% *}" != "200" ] || { [ -n "$want" ] && ! printf '%s' "$answer" | grep -q "$want"; }; then
      missing="$missing $asset"
    fi
  done
  [ -n "$missing" ] && trouble+=("клиент выложен наполовину: не отдаётся${missing} — мессенджер откроется голой разметкой, без оформления")
fi

# 4. База.
if ! su - postgres -c "psql -tAc 'select 1' messenger" >/dev/null 2>&1; then
  trouble+=("база не отвечает")
fi

# 5. Ретранслятор голоса слушает свой порт.
if ! ss -uln 2>/dev/null | grep -q ':3478 '; then
  trouble+=("ретранслятор голоса не слушает порт 3478")
fi

# 6. Диск. Кончится — встанет и база, и загрузка файлов, причём молча.
used=$(df --output=pcent / | tail -1 | tr -dc '0-9')
[ "${used:-0}" -ge 90 ] && trouble+=("диск занят на ${used}%")

# 7. Память. Свопа здесь нет, и при нехватке система начинает убивать
#    процессы — чаще всего не тот, который виноват.
free_mb=$(free -m | awk '/^Mem:/{print $7}')
[ "${free_mb:-1000}" -lt 80 ] && trouble+=("свободной памяти всего ${free_mb} МБ")

# ── Решение ───────────────────────────────────────────────────────

notify() {
  echo "$1"
  if [ -z "$TELEGRAM_TOKEN" ] || [ -z "$TELEGRAM_CHAT" ]; then
    echo "(в Телеграм не отправлено: бот не настроен, см. monitor.env)"
    return 0
  fi

  # Телеграм не принимает больше 4096 символов, а в тревоге есть хвост
  # журнала — строки там бывают длинные. Обрезаем с запасом: лучше
  # прийти укороченной, чем не прийти вовсе.
  local text=${1:0:3500}
  local answer
  answer=$(curl -s -m 20     "https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage"     --data-urlencode "chat_id=${TELEGRAM_CHAT}"     --data-urlencode "text=$text")

  # Ответ проверяем обязательно. Раньше он выбрасывался в /dev/null,
  # и curl молчал при любом отказе Телеграма: в журнале значилось бы,
  # что тревога ушла, а на телефон не приходило бы ничего. Такой сторож
  # хуже, чем никакого, — на него надеются.
  if printf '%s' "$answer" | grep -q '"ok":true'; then
    echo "(отправлено в Телеграм)"
  else
    echo "(В ТЕЛЕГРАМ НЕ УШЛО. Ответ: ${answer:-нет ответа})"
  fi
}

streak=$(cat "$STATE/streak" 2>/dev/null || echo 0)
was=$(cat "$STATE/state" 2>/dev/null || echo ok)

if [ ${#trouble[@]} -eq 0 ]; then
  echo 0 > "$STATE/streak"
  if [ "$was" = "fail" ]; then
    echo ok > "$STATE/state"
    # Вместе с временем — чем болел. Одно «лежал с 21:55» заставляет
    # гадать: то ли сервер падал, то ли база, то ли связь. Причина
    # хранится с той же минуты, что и время.
    notify "✅ Снова всё в порядке.
Не работало с $(cat "$STATE/since" 2>/dev/null || echo '?').
Было так: $(cat "$STATE/why" 2>/dev/null || echo 'причина не записана')."
  else
    echo "всё живо"
  fi
  exit 0
fi

streak=$((streak + 1))
echo "$streak" > "$STATE/streak"

if [ "$streak" -lt "$LIMIT" ]; then
  echo "неполадка ($streak из $LIMIT): ${trouble[*]}"
  exit 0
fi

# Второй раз подряд — это уже не моргание.
if [ "$was" != "fail" ]; then
  echo fail > "$STATE/state"
  date '+%d.%m.%Y %H:%M' > "$STATE/since"
  printf '%s; ' "${trouble[@]}" > "$STATE/why"
  tail_log=$(journalctl -u messenger -n 5 --no-pager -o cat 2>/dev/null | tail -5)
  notify "🔴 Мессенджер не работает.

Что не так:
$(printf '• %s\n' "${trouble[@]}")

Последнее в журнале:
${tail_log:-(пусто)}"
else
  echo "всё ещё лежит: ${trouble[*]}"
fi
